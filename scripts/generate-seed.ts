/**
 * Writes sql/seed.sql from src/data/seedRoster.ts (the roster from the PDF).
 * Run: npm run seed:generate. Never hand-edit seed.sql.
 *
 * The seed is meant for an EMPTY database (first-time setup): it inserts with
 * fixed ids 1, 2, 3 …, so on a database with data it fails on the first row.
 */
import { writeFileSync } from 'node:fs';
import { buildSeed } from '../src/data/seedRoster.ts';

const data = buildSeed();
const q = (v: string | number | null) => (v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${v.replace(/\\/g, '\\\\').replace(/'/g, "''")}'`);
const rows = (table: string, cols: string[], values: (string | number | null)[][]) =>
  values.length ? `INSERT INTO ${table} (${cols.join(', ')}) VALUES\n${values.map((v) => `  (${v.map(q).join(', ')})`).join(',\n')};\n` : '';

const roster = data.rosters[0];
let timeId = 0;
const sql = [
  '-- GENERATED by scripts/generate-seed.ts from src/data/seedRoster.ts. Do not edit by hand.',
  '-- Run once, after sql/schema.sql, on an empty database.',
  '',
  'SET NAMES utf8mb4;',
  "SET time_zone = '+07:00';",
  '',
  '-- First-time setup only: it uses fixed ids, so on a database that already has',
  '-- data the first INSERT fails with "Duplicate entry" and nothing is changed.',
  '',
  'START TRANSACTION;',
  '',
  rows('teachers', ['id', 'title', 'name', 'active'], data.teachers.map((t) => [t.id, t.title, t.name, 1])),
  rows('duty_groups', ['id', 'label_en', 'label_id', 'scope', 'sort'], data.groups.map((g, i) => [g.id, g.labelEn, g.labelId, g.scope, i + 1])),
  rows('rosters', ['id', 'title', 'released_on', 'effective_from'], [[roster.id, roster.title, roster.releasedOn, roster.effectiveFrom]]),
  rows('sections', ['id', 'roster_id', 'name_en', 'name_id', 'sort'], roster.sections.map((s) => [s.id, roster.id, s.nameEn, s.nameId, s.sort])),
  rows('duties', ['id', 'section_id', 'label', 'note', 'timing', 'sort'], roster.duties.map((d) => [d.id, d.sectionId, d.label, d.note, d.timing, d.sort])),
  rows(
    'duty_times',
    ['id', 'duty_id', 'weekday', 'start_time', 'end_time'],
    roster.duties.flatMap((d) => d.times.map((t) => [++timeId, d.id, t.weekday, `${t.start}:00`, `${t.end}:00`])),
  ),
  rows('assignments', ['duty_id', 'weekday', 'teacher_id', 'group_id'], roster.assignments.map((a) => [a.dutyId, a.weekday, a.teacherId, a.groupId])),
  "INSERT INTO meta (k, v) VALUES ('version', '1') ON DUPLICATE KEY UPDATE v = CAST(v AS UNSIGNED) + 1;",
  '',
  'COMMIT;',
  '',
].join('\n');

writeFileSync('sql/seed.sql', sql);
console.log(`sql/seed.sql: ${data.teachers.length} teachers, ${data.groups.length} groups, ${roster.duties.length} duties, ${roster.assignments.length} cells.`);
