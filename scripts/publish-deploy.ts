/**
 * Builds the app and publishes it to the `deploy` branch on GitHub:
 * dist/ (index.html, assets, icons, .htaccess) + api/ + tools/ + sql/ + deploy.sh.
 * On the server (cPanel Terminal), ~/repositories/dutyboard is a clone of
 * that branch; `git pull && bash deploy.sh` there copies the site files into
 * public_html/duty (tools/ and sql/ stay in the clone, outside the web root).
 * Run: npm run deploy (GitHub Actions runs it on every push to main).
 */
import { execFileSync, execSync } from 'node:child_process';
import { cpSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const BRANCH = 'deploy';
const SERVER_CMD = 'cd ~/repositories/dutyboard && git pull && bash deploy.sh';

// Runs on the server. Copies the site (not tools/, sql/ or this script) into
// the subdomain's folder; old hashed assets are removed first.
const DEPLOY_SH = `#!/bin/bash
# Generated by scripts/publish-deploy.ts. Run on the server:
#   ${SERVER_CMD}
set -e
cd "$(dirname "$0")"
DEST="$HOME/public_html/duty"
mkdir -p "$DEST"
rm -rf "$DEST/assets"
for f in * .htaccess; do
  case "$f" in deploy.sh|tools|sql|README.md) continue ;; esac
  cp -R "$f" "$DEST/"
done
echo "Deployed $(git log -1 --format=%s) to $DEST"
`;

const README = `# deploy branch (generated — do not edit)

Built by scripts/publish-deploy.ts from \`main\`. On the server:

    ${SERVER_CMD}

First-time setup and the admin password tool (tools/set-password.php): see README.md on \`main\`.
`;

const git = (args: string[], cwd = '.') => execFileSync('git', args, { cwd, encoding: 'utf8' }).trim();

function fail(msg: string): never {
  console.error(`\n✗ ${msg}\n`);
  process.exit(1);
}

// A production build must talk to the PHP API, never run in demo mode.
if (process.env.VITE_API && process.env.VITE_API !== 'php') fail(`VITE_API is "${process.env.VITE_API}": the live site would not use the PHP API.`);
if (git(['status', '--porcelain'])) fail('You have uncommitted changes. Commit (and push) them first, so the live site matches GitHub.');

const sha = git(['rev-parse', '--short', 'HEAD']);
const subject = git(['log', '-1', '--format=%s']);

execSync('npm run build', { stdio: 'inherit' });

const hasRemote = git(['ls-remote', '--heads', 'origin', BRANCH]) !== '';
if (hasRemote) git(['fetch', 'origin', BRANCH]);

const dir = mkdtempSync(join(tmpdir(), 'duty-deploy-'));
try {
  git(hasRemote ? ['worktree', 'add', '-B', BRANCH, dir, `origin/${BRANCH}`] : ['worktree', 'add', '--orphan', '-b', BRANCH, dir]);

  // Replace everything with the fresh build (keep the worktree's .git file).
  for (const f of readdirSync(dir)) if (f !== '.git') rmSync(join(dir, f), { recursive: true, force: true });
  cpSync('dist', dir, { recursive: true });
  for (const d of ['api', 'tools', 'sql']) cpSync(d, join(dir, d), { recursive: true });
  writeFileSync(join(dir, 'deploy.sh'), DEPLOY_SH);
  writeFileSync(join(dir, 'README.md'), README);

  git(['add', '-A'], dir);
  if (!git(['status', '--porcelain'], dir)) {
    console.log(`\nNothing changed — the ${BRANCH} branch already has this build.\n`);
  } else {
    git(['commit', '-m', `Build of ${sha}: ${subject}`], dir);
    execFileSync('git', ['push', 'origin', BRANCH], { cwd: dir, stdio: 'inherit' });
    console.log(`\n✓ Pushed build of ${sha} to the ${BRANCH} branch.`);
    console.log('  Now in cPanel → Terminal, run:');
    console.log(`  ${SERVER_CMD}\n`);
  }
} finally {
  git(['worktree', 'remove', '--force', dir]);
}
