const dictionaries: Record<Lang, Record<MessageKey, string>> = { en, id };

export type T = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>) {
  let s = dictionaries[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: T; errorText: (code: ErrorCode) => string };
const I18nContext = createContext<Ctx | null>(null);

/** Language: ?lang=id in the URL (handy for a TV), else the last choice, else English. */
function initialLang(): Lang {
  const q = typeof window !== 'undefined' ? new URLSearchParams(window.location.search).get('lang') : null;
  if (q === 'id' || q === 'en') return q;
  return load<string>(KEYS.lang, 'en') === 'id' ? 'id' : 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    save(KEYS.lang, l);
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const value = useMemo<Ctx>(() => {
    const t: T = (key, vars) => translate(lang, key, vars);
    return { lang, setLang, t, errorText: (code) => t(`e_${code}` as MessageKey) };
  }, [lang, setLang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
